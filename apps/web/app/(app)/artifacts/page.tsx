// ─── Type config ─────────────────────────────────────────────────────────────

const TYPE_CONFIG: Record<ArtifactType, { badge: string; label: string }> = {
  JSON:     { badge: "border-violet-200 bg-violet-50 text-violet-700", label: "JSON" },
  Markdown: { badge: "border-blue-200 bg-blue-50 text-blue-700",       label: "MD" },
  CSV:      { badge: "border-emerald-200 bg-emerald-50 text-emerald-700", label: "CSV" },
  PDF:      { badge: "border-red-200 bg-red-50 text-red-700",           label: "PDF" },
};

// ─── Filter chip ─────────────────────────────────────────────────────────────

function FilterChip({ label, active, onClick }: { label: string; active: boolean; onClick: () => void }) {
  return (
    <button
      type="button"
      onClick={onClick}
      className={cn(
        "h-7 rounded-full border px-3 text-[11px] font-medium transition-colors",
        active
          ? "border-primary bg-primary text-primary-foreground"
          : "border-border bg-background text-muted-foreground hover:border-foreground/30 hover:text-foreground",
      )}
    >
      {label}
    </button>
  );
}

// ─── Page ────────────────────────────────────────────────────────────────────

