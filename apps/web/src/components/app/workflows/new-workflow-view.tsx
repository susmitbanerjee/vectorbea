/**
 * A create failure, said in terms of what the user can do about it.
 *
 * The API's own message is shown verbatim whenever it has one — the validation
 * messages this endpoint produces are specific ("Invalid cron expression '…' —
 * expected 5 fields") and rewriting them into something generic would throw the
 * only useful sentence away.
 */
function CreateFailure({ error }: { error: VectorbeaApiError }) {
  const title =
    error.intent === "validation" ? "The workflow was not created"
      : error.intent === "forbidden" ? "You cannot create workflows in this workspace"
        : error.intent === "rate_limited" ? "Too many requests"
          : "The workflow could not be created";

  const fix =
    error.intent === "validation" ? "Fix the field it names above and try again."
      : error.intent === "forbidden" ? "Ask a workspace admin for the editor role."
        : error.isRetryable ? "Nothing was created. Try again."
          : "Nothing was created.";

  return (
    <Notice tone="failed" title={title}>
      {error.message} {fix}
      <span className="text-fg-disabled font-code text-mono-sm mt-1 block">{error.supportReference}</span>
    </Notice>
  );
}

/* ── Chrome ───────────────────────────────────────────────────────────────── */

function Panel({
  title, help, children,
}: {
  title: string;
  help?: string;
  children: React.ReactNode;
}) {
  return (
    <section className="border-subtle bg-surface-raised rounded-lg border">
      <header className="border-subtle border-b px-3 py-2">
        <Text variant="eyebrow" tone="muted">{title}</Text>
        {help ? (
          <Text variant="caption" tone="muted" className="mt-0.5 block leading-snug">{help}</Text>
        ) : null}
      </header>
      <div className="p-3">{children}</div>
    </section>
  );
}

function Notice({
  tone, title, children,
}: {
  tone: "failed" | "waiting";
  title: string;
  children: React.ReactNode;
}) {
  return (
    <div
      role="alert"
      className={cn(
        "rounded-md border p-2.5",
        tone === "failed"
          ? "border-status-failed-border bg-status-failed-subtle"
          : "border-status-waiting-border bg-status-waiting-subtle",
      )}
    >
      <Text
        variant="body-sm"
        tone="inherit"
        className={cn("block font-medium", tone === "failed" ? "text-status-failed" : "text-status-waiting")}
      >
        {title}
      </Text>
      <Text variant="body-sm" tone="secondary" className="mt-0.5 block leading-snug">{children}</Text>
    </div>
  );
}
