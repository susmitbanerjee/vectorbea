/* ══════════════════════════════════════════════════════════════════════════════
   NEW WORKFLOW

   Three ways in, and the page's job is to make the choice between them cheap
   rather than to hide two of them behind the third. The Architect is the
   recommended path and gets the space; the manual form is RIGHT THERE, filled
   in and submittable, because somebody who already knows what they want should
   not have to click through a chooser to type a name.

   IT CREATES IN TWO CALLS, NOT ONE, and that is the API's shape rather than an
   accident here. `POST /api/workflows` writes the row — name, slug,
   description, status — and knows nothing about triggers. The trigger lives on
   a VERSION, and `POST /api/workflows/:id/versions` is also what materialises
   the `schedules` row through `syncSchedule`. A workflow created without a
   version is a workflow that will never fire, however carefully its cron was
   typed, so the second call is not optional and its failure is reported rather
   than swallowed.

   The success state stays ON THIS PAGE instead of redirecting. The workflow
   detail and builder routes still read from fixtures, so pushing a freshly
   created real id at them lands on a 404 — an outcome that reads as "the create
   failed" when it in fact succeeded. Naming the id here, with the list one
   click away, is the honest version until those routes are migrated.
══════════════════════════════════════════════════════════════════════════════ */

type TriggerKind = "manual" | "cron" | "webhook" | "api";

interface TriggerOption {
  id: TriggerKind;
  label: string;
  blurb: string;
  /** What the operator has to do next for this trigger to actually fire. */
  next: string;
}

const TRIGGERS: TriggerOption[] = [
  {
    id: "manual",
    label: "Manual",
    blurb: "Someone presses run.",
    next: "Nothing else to set up — run it from the workflow page.",
  },
  {
    id: "cron",
    label: "Schedule",
    blurb: "A cron expression, in a timezone you pick.",
    next: "The schedule is created with the workflow and starts firing once you publish.",
  },
  {
    id: "webhook",
    label: "Webhook",
    blurb: "An inbound HTTP call starts a run.",
    next: "The endpoint and its signing secret are issued after the first publish.",
  },
  {
    id: "api",
    label: "API",
    blurb: "Started programmatically with a workspace key.",
    next: "Call POST /api/workflows/:id/run with an API key.",
  },
];

const DEFAULT_CRON = "0 9 * * 1-5";

function defaultTimezone(): string {
  try { return Intl.DateTimeFormat().resolvedOptions().timeZone || "UTC"; } catch { return "UTC"; }
}

/**
 * The starting graph: one trigger node and nothing else.
 *
 * Shaped exactly like the graphs the Architect compiles
 * (`WorkflowArchitectService.compilePlanToGraphJson`) — `{ id, type, position,
 * data }` with `data.nodeType` mirrored — so a workflow created by hand and one
 * generated by the Architect are the same object to the builder and to the
 * engine. An empty `{ nodes: [], edges: [] }` would also validate, but it opens
 * the builder onto a blank canvas with no entry point, and the trigger the user
 * just chose would exist only in `triggerConfig`.
 */
function initialGraph(trigger: TriggerKind, label: string): Record<string, unknown> {
  return {
    nodes: [
      {
        id: "trigger_1",
        type: "trigger",
        position: { x: 120, y: 60 },
        data: {
          label,
          nodeType: "trigger",
          description: `Workflow trigger (${trigger})`,
          triggerConfig: { type: trigger },
        },
      },
    ],
    edges: [],
  };
}

/**
 * `triggerConfig` as `syncSchedule` reads it.
 *
 * Both `triggerType` and `type` are written because the Kotlin side accepts
 * either and the two generations of graph in this repo disagree about which one
 * they use — writing one key only is how a schedule silently fails to appear.
 */
function triggerConfigFor(trigger: TriggerKind, cron: string, timezone: string): Record<string, unknown> {
  if (trigger !== "cron") return { triggerType: trigger, type: trigger };
  return {
    triggerType: "cron",
    type: "cron",
    cronExpression: cron.trim(),
    cron: cron.trim(),
    timezone,
  };
}

interface Created {
  id: string;
  name: string;
  /** False when the row was written but its first version was not. */
  versioned: boolean;
  versionError: string | null;
}

export function NewWorkflowView() {
  const api = useApi();
  const queryClient = useQueryClient();
  const scope = useScope();
  const environment = useEnvironmentUuid();

  const [name, setName] = React.useState("");
  const [description, setDescription] = React.useState("");
  const [trigger, setTrigger] = React.useState<TriggerKind>("manual");
  const [cron, setCron] = React.useState(DEFAULT_CRON);
  const [timezone, setTimezone] = React.useState<string | null>(null);
  const [created, setCreated] = React.useState<Created | null>(null);
  /** Set once the user has tried to submit — validation before that is nagging. */
  const [submitted, setSubmitted] = React.useState(false);

  React.useEffect(() => { setTimezone(defaultTimezone()); }, []);

  const trimmedName = name.trim();
  const zone = timezone ?? "UTC";
  // Validated client-side as well as server-side on purpose: the API rejects a
  // bad cron with a 400 that costs a round trip, and the workflow row is
  // written before the version is, so a cron typo would leave a half-configured
  // workflow behind for the sake of a check the form can do instantly.
  const cronInvalid = trigger === "cron" && !evaluateCron(cron, zone, 1).valid;

  const nameError = submitted && !trimmedName
    ? "Give the workflow a name. It is what you will search for in run history."
    : undefined;
  const cronError = submitted && cronInvalid
    ? "This is not a five-field cron expression. Use minute hour day month weekday — for example 0 9 * * 1-5 for 09:00 on weekdays."
    : undefined;

  const create = useApiMutation<Created, void>({
    mutationFn: async () => {
      const environmentId = environment.environmentId;
      // Guarded again here rather than trusted from the disabled button: the
      // create endpoint 400s without a real environment id, and a 400 that says
      // "X-Environment-Id header is required" is not something a user can act on.
      if (!environmentId) {
        throw new Error("No environment resolved yet.");
      }
      const writeScope = { workspaceId: scope.workspaceId, environmentId };

      const workflow = await api.workflows.create(
        {
          name: trimmedName,
          description: description.trim() || null,
          status: "draft",
        },
        writeScope,
      );

      // The version is a SEPARATE failure. Reporting it separately matters:
      // the workflow genuinely exists at this point, and telling somebody
      // "creation failed" would send them to create a second one.
      let versioned = true;
      let versionError: string | null = null;
      try {
        await api.workflows.createVersion(
          workflow.id,
          {
            graph: initialGraph(trigger, TRIGGERS.find((t) => t.id === trigger)?.label ?? "Start"),
            triggerConfig: triggerConfigFor(trigger, cron, zone),
          },
          writeScope,
        );
      } catch (error) {
        versioned = false;
        versionError = error instanceof Error ? error.message : "The first version could not be written.";
      }

      return { id: workflow.id, name: workflow.name, versioned, versionError };
    },
    onSuccess: (result) => {
      setCreated(result);
      // The list is the only place the new workflow is visible right now, so it
      // has to be right the moment the user clicks through to it.
      void queryClient.invalidateQueries({ queryKey: queryKeys.workflows.all(scope) });
    },
  });

  const blocked = environment.unresolved;
  const busy = create.isPending;

  function submit(event: React.FormEvent) {
    event.preventDefault();
    setSubmitted(true);
    if (!trimmedName || cronInvalid || blocked || busy) return;
    create.mutate();
  }

  function reset() {
    setCreated(null);
    setSubmitted(false);
    setName("");
    setDescription("");
    setTrigger("manual");
    setCron(DEFAULT_CRON);
    create.reset();
  }

  return (
    <PageContainer>
      <PageHeader
        eyebrow={
          <Link
            href={"/workflows" as Route}
            className="rounded-xs outline-none transition-colors duration-fast hover:text-fg-secondary focus-visible:focus-ring"
          >
            Build · Workflows
          </Link>
        }
        title="New workflow"
        description="Describe what you want and let the Architect draft it, or set up the shell yourself and build the graph on the canvas. Either way it starts as a draft — nothing runs until you publish."
      />

      {created ? (
        <CreatedPanel created={created} onAnother={reset} />
      ) : (
        <div className="grid items-start gap-4 lg:grid-cols-[minmax(0,1fr)_minmax(0,1fr)]">
          <div className="grid gap-3">
            <ArchitectCard />
            <SecondaryPaths />
          </div>

          <Panel
            title="Build it yourself"
            help="Creates the workflow and its first version, then opens on the canvas when you are ready."
          >
            <form onSubmit={submit} className="grid gap-3" noValidate>
              <Field
                label="Name"
                required
                description="What it is called in the list, in run history and in alerts."
                error={nameError}
                characterCount={{ value: name.length, max: 255 }}
              >
                <Input
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder="Renewal outreach"
                  maxLength={255}
                  autoComplete="off"
                />
              </Field>

              <Field
                label="Description"
                description="Optional. One line on what it does and who relies on it."
              >
                <Textarea
                  value={description}
                  onChange={(e) => setDescription(e.target.value)}
                  placeholder="Finds contracts renewing in the next 30 days and drafts outreach for each account."
                  minRows={2}
                  maxRows={6}
                />
              </Field>

              <fieldset className="grid gap-1.5">
                <legend className="font-ui text-label text-fg-secondary mb-1.5">Trigger</legend>
                <div className="grid gap-1.5 sm:grid-cols-2">
                  {TRIGGERS.map((option) => (
                    <TriggerChoice
                      key={option.id}
                      option={option}
                      checked={trigger === option.id}
                      onSelect={() => setTrigger(option.id)}
                    />
                  ))}
                </div>
                <Text variant="caption" tone="muted" className="mt-0.5 block leading-snug">
                  {TRIGGERS.find((t) => t.id === trigger)?.next}
                </Text>
              </fieldset>

              {trigger === "cron" ? (
                <div className="grid gap-3 sm:grid-cols-[minmax(0,1.4fr)_minmax(0,1fr)]">
                  <Field
                    label="Schedule"
                    required
                    description="Five fields, in the timezone beside it."
                    error={cronError}
                  >
                    <CronInput value={cron} onValueChange={setCron} timezone={zone} previewCount={3} />
                  </Field>
                  <Field label="Timezone" description="Occurrences above are shown in it.">
                    <TimezonePicker value={timezone} onValueChange={setTimezone} />
                  </Field>
                </div>
              ) : null}

              {blocked ? (
                <Notice
                  tone="failed"
                  title={environment.foreign ? "No environment for this workspace" : "No environment resolved"}
                >
                  {environment.foreign
                    ? "The only environment this deployment can name belongs to a different workspace, so it cannot be used here without writing your data into another workspace. The API has no per-workspace environment endpoint yet — see docs/integration/API-GAPS.md."
                    : "Creating a workflow needs this workspace’s environment id, and the API could not be reached to resolve it. Reload once the API is up — nothing has been lost."}
                </Notice>
              ) : null}

              {create.error ? <CreateFailure error={create.error} /> : null}

              <div className="border-subtle mt-1 flex flex-wrap items-center justify-between gap-2 border-t pt-3">
                <Button asChild variant="ghost" size="sm">
                  <Link href={"/workflows" as Route}>Cancel</Link>
                </Button>
                <Button
                  type="submit"
                  variant="primary"
                  size="sm"
                  loading={busy}
                  disabled={blocked || environment.loading}
                >
                  Create workflow
                </Button>
              </div>
            </form>
          </Panel>
        </div>
      )}
    </PageContainer>
  );
}

